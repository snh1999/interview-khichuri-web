import { useMemo, useState } from "react";
import { type IJob, useGetJobs } from "@/api/jobs";
import type { IResume } from "@/api/resumes";
import {
  type TAtsScore,
  useAtsScoreEntries,
  useGetResumes,
  useScoreResume,
} from "@/api/resumes";
import { AiActionButton } from "@/components/common/ai/AiActionButton.tsx";
import { AppCombobox } from "@/components/common/form/combobox/AppCombobox.tsx";
import { ATSReviewCard } from "@/components/resume/ats/ATSReviewCard.tsx";
import { resumeToText } from "@/components/resume/utils.ts";
import { Button } from "@/components/ui/button.tsx";
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card.tsx";
import { atsScoreCopyPrompt } from "@/lib/ai/prompts.ts";
import type { IAtsCacheEntry, IAtsScoreFilter } from "@/lib/storage/indexdb.ts";

interface IProps {
  job?: IJob;
}

const MAX_DEFAULT_ENTRIES = 5;

interface IHistorySummaryProps {
  total: number;
  visible: number;
  showAll: boolean;
  onToggle: () => void;
}

const HistorySummary = ({
  total,
  visible,
  showAll,
  onToggle,
}: Readonly<IHistorySummaryProps>) => (
  <div className="flex items-center justify-between gap-2">
    <p className="text-muted-foreground text-xs">
      {showAll
        ? `Showing all ${total} saved reviews.`
        : `Showing ${visible} of ${total} saved reviews.`}
    </p>
    <Button onClick={onToggle} size="sm" variant="ghost">
      {showAll ? "Show recent" : "Show all"}
    </Button>
  </div>
);

const toFullScore = (entry: IAtsCacheEntry): TAtsScore => ({
  overall: entry.overall,
  categories: entry.categories,
  recommendations: entry.recommendations,
  matchedKeywords: entry.matchedKeywords,
  missingKeywords: entry.missingKeywords,
  tailoringNotes: entry.tailoringNotes,
});

export const ATSReview = ({ job }: Readonly<IProps>) => {
  const { data: jobsData } = useGetJobs();
  const { data: resumesData } = useGetResumes();
  const jobs = jobsData ?? [];
  const resumes = resumesData ?? [];
  const scoreMutation = useScoreResume();

  const [selectedJobId, setSelectedJobId] = useState<string | null>(null);
  const [selectedResumeId, setSelectedResumeId] = useState<string | null>(null);
  const [showAll, setShowAll] = useState(false);

  const jobId = job ? job.id : selectedJobId;

  const filter = useMemo<IAtsScoreFilter>(
    () => ({
      ...(jobId ? { jobId } : {}),
      ...(selectedResumeId ? { resumeId: selectedResumeId } : {}),
    }),
    [jobId, selectedResumeId]
  );

  const jobMap = useMemo(() => new Map(jobs.map((j) => [j.id, j])), [jobs]);
  const resumeMap = useMemo(
    () => new Map(resumes.map((r) => [r.id, r])),
    [resumes]
  );

  const { data = [] } = useAtsScoreEntries(filter);
  const hasFilter = jobId !== null || selectedResumeId !== null;
  const owned = data.filter((entry) => resumeMap.has(entry.resumeId));
  const entries =
    hasFilter || showAll ? owned : owned.slice(0, MAX_DEFAULT_ENTRIES);

  const handleGenerate = async (
    provider: string,
    model?: string,
    instruction?: string
  ) => {
    if (!(jobId && selectedResumeId)) {
      return;
    }
    await scoreMutation.mutateAsync({
      jobId,
      resumeId: selectedResumeId,
      provider,
      model,
      instruction,
    });
  };

  const handleJobChange = (value: string | number | null) =>
    setSelectedJobId(value === null ? null : String(value));

  const handleToggleShowAll = () => setShowAll((value) => !value);

  const jobToOption = (j: IJob) => ({
    value: j.id,
    label: `${j.title} @ ${j.companyName}`,
  });

  const handleResumeChange = (value: string | number | null) =>
    setSelectedResumeId(value === null ? null : String(value));

  const resumeToOption = (r: IResume) => ({ value: r.id, label: r.name });

  const copyPrompt = useMemo(() => {
    if (!(jobId && selectedResumeId)) {
      return;
    }
    const target = jobMap.get(jobId) ?? job;
    return atsScoreCopyPrompt({
      companyName: target?.companyName,
      jobDescription: target?.description,
      jobTitle: target?.title,
      resumeText: resumeToText(resumeMap.get(selectedResumeId)?.content),
    });
  }, [job, jobId, jobMap, resumeMap, selectedResumeId]);

  return (
    <Card className="px-1">
      <CardHeader className="border-b">
        <CardTitle className="flex items-center gap-2">Resume Review</CardTitle>
        <CardDescription>
          Generated by comparing your resume with the selected job using AI.
          Results are cached locally and never stored on the server.
        </CardDescription>
        <CardAction>
          <AiActionButton
            copyPrompt={copyPrompt}
            description={
              job
                ? `Score this resume against ${job.title} @ ${job.companyName}.`
                : "Select a job and a resume to compare with AI."
            }
            execute={handleGenerate}
            executeDisabled={!(jobId && selectedResumeId)}
            executeLabel="Run review"
            isLoading={scoreMutation.isPending}
            showInstruction
            size="sm"
            title="Generate AI Resume Review"
            toastErrorMessage="Failed to generate AI resume review"
            toastSuccessMessage="AI resume review generated"
          >
            {job ? (
              <p className="text-foreground text-sm">
                Job: {job.title} at {job.companyName}
              </p>
            ) : (
              <AppCombobox
                data={jobs}
                label="Job"
                onChange={handleJobChange}
                placeholder="Select a job..."
                toOption={jobToOption}
                value={selectedJobId}
              />
            )}

            <AppCombobox
              data={resumes}
              label="Resume"
              onChange={handleResumeChange}
              placeholder="Select a resume..."
              toOption={resumeToOption}
              value={selectedResumeId}
            />
          </AiActionButton>
        </CardAction>
      </CardHeader>
      <CardContent className="flex flex-col gap-5">
        <div className="grid gap-4 sm:grid-cols-2">
          {job ? null : (
            <AppCombobox
              data={jobs}
              label="Job"
              onChange={handleJobChange}
              placeholder="Select a job..."
              toOption={jobToOption}
              value={selectedJobId}
            />
          )}

          <AppCombobox
            data={resumes}
            label="Resume"
            onChange={handleResumeChange}
            placeholder="Select a resume..."
            toOption={resumeToOption}
            value={selectedResumeId}
          />
        </div>

        {entries.length === 0 ? (
          <CardDescription className="text-center italic">
            {hasFilter
              ? "No saved scores for this selection yet. Run the review to create one."
              : "Select a job and a resume, then run the review."}
          </CardDescription>
        ) : (
          <div className="flex flex-col gap-5">
            {entries.map((entry) => {
              const relatedJob = jobMap.get(entry.jobId);
              const relatedResume = resumeMap.get(entry.resumeId);
              return (
                <ATSReviewCard
                  companyName={relatedJob?.companyName}
                  jobTitle={relatedJob?.title}
                  key={`${entry.jobId}|${entry.resumeId}`}
                  resumeName={relatedResume?.name}
                  score={toFullScore(entry)}
                />
              );
            })}

            {!hasFilter && owned.length > MAX_DEFAULT_ENTRIES ? (
              <HistorySummary
                onToggle={handleToggleShowAll}
                showAll={showAll}
                total={owned.length}
                visible={entries.length}
              />
            ) : null}
          </div>
        )}
      </CardContent>
    </Card>
  );
};
